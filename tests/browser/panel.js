// Runs against an isolated in-memory application and temporary environment file.
// No customer credentials, existing .env, or external providers are used.
import assert from 'node:assert/strict';
import { mkdtemp, writeFile, mkdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { once } from 'node:events';
import { bootstrap } from '../../src/bootstrap.js';
import { config } from '../../src/config/env.js';
import { createHttpServer } from '../../src/http/app.js';

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const directory=await mkdtemp(join(tmpdir(),'convo-browser-'));
const envPath=join(directory,'.env');
await writeFile(envPath,'APP_MODE=mock\n',{mode:0o600});
const c=await bootstrap({config:config({APP_MODE:'mock'}),envPath,log:()=>{}});
await c.operators.create('browser@example.test','browser-only-password-123','admin');
const server=await createHttpServer(c);
let browser,timer;
const errors=[];
try {
  server.listen(0,'127.0.0.1');await once(server,'listening');
  c.config.publicUrl=`http://127.0.0.1:${server.address().port}`;
  browser=await chromium.launch({headless:true,...(process.env.BROWSER_EXECUTABLE_PATH?{executablePath:process.env.BROWSER_EXECUTABLE_PATH}:{}),args:['--disable-dev-shm-usage']});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  page.on('pageerror',error=>errors.push(error.message));
  timer=setInterval(()=>c.worker.tick(30).catch(error=>errors.push(error.message)),250);
  await mkdir('artifacts',{recursive:true});
  await page.goto(c.config.publicUrl);
  await page.screenshot({path:'artifacts/panel-login.png',fullPage:true});
  await page.getByLabel('Work email',{exact:true}).fill('browser@example.test');
  await page.getByLabel('Password',{exact:true}).fill('browser-only-password-123');
  await page.getByRole('button',{name:'Sign in to workspace'}).click();
  await page.getByRole('heading',{level:1,name:'Overview',exact:true}).waitFor();
  await page.locator('.loading-state').waitFor({state:'hidden'});
  await page.screenshot({path:'artifacts/panel-overview.png',fullPage:true});
  async function visit(route,title){await page.locator(`.nav-item[href="#${route}"]`).click();await page.getByRole('heading',{level:1,name:title,exact:true}).waitFor();await page.locator('.loading-state').waitFor({state:'hidden'});assert.equal(await page.getByText('We couldn’t load this page',{exact:true}).count(),0);}
  for(const [route,title] of [['inbox','Conversations'],['orders','Orders'],['catalog','Product catalog'],['checkouts','Checkout sessions'],['operations','Delivery & jobs'],['team','Team & access'],['activity','Activity log'],['settings','Workspace settings'],['integrations','Integrations'],['simulator','Test lab']])await visit(route,title);
  await page.getByLabel('Customer message',{exact:true}).fill('buy 102 x1');
  await page.getByRole('button',{name:'Send customer message'}).click();
  await page.locator('.lab-phone').getByText('Complete the checkout Flow sent to you.').waitFor();
  await page.getByRole('button',{name:'Open latest checkout'}).click();
  for(let i=0;i<3;i++){await page.locator('#modal').getByRole('button',{name:'Continue',exact:true}).click();await page.waitForTimeout(100);}
  await page.getByLabel('I confirm this order and the displayed total').check();
  await page.locator('#modal').getByRole('button',{name:'Confirm order',exact:true}).click();
  await page.locator('#modal').getByRole('heading',{name:'Order created',exact:true}).waitFor();
  await page.locator('#modal').getByRole('button',{name:'Done',exact:true}).click();
  assert.equal(await page.getByLabel('Order ID',{exact:true}).inputValue(),'5001');
  await page.getByRole('button',{name:'Simulate verified payment',exact:true}).click();
  await page.locator('.lab-phone').getByText(/Payment verified for order #5001/).waitFor();
  await page.screenshot({path:'artifacts/panel-test-lab.png',fullPage:true});
  await visit('orders','Orders');
  await page.getByRole('button',{name:'#5001',exact:true}).click();
  await page.locator('#modal').getByText('Payment verified',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Close dialog',exact:true}).click();
  await visit('settings','Workspace settings');
  await page.getByLabel('Workspace name',{exact:true}).fill('Browser Test Store');
  await page.getByRole('button',{name:'Save changes',exact:true}).click();
  await page.getByText('Workspace settings saved and applied.',{exact:true}).waitFor();
  assert.equal((await c.settings.read()).values.storeName,'Browser Test Store');
  await visit('integrations','Integrations');
  const ai=page.locator('.provider-card').filter({has:page.getByRole('heading',{name:'AI provider',exact:true})});
  await ai.getByRole('button',{name:'Configure',exact:true}).click();
  await page.getByLabel('AI provider',{exact:true}).selectOption('ollama');
  await page.route('**/api/operator/ai/models',route=>route.fulfill({json:{provider:'ollama',models:[{id:'browser-local-tool-model',name:'Browser local model',toolSupport:'unverified'}],truncated:false}}));
  await page.getByRole('button',{name:'Load available models',exact:true}).click();
  await page.getByRole('status').filter({hasText:'1 model loaded'}).waitFor();
  await page.getByLabel('Available AI models',{exact:true}).selectOption('browser-local-tool-model');
  await page.getByRole('button',{name:'Save AI configuration',exact:true}).click();
  await page.locator('#modal').waitFor({state:'hidden'});
  assert.equal((await c.settings.envDocument()).values.AI_PROVIDER,'ollama');
  assert.equal((await c.settings.envDocument()).values.OLLAMA_MODEL,'browser-local-tool-model');
  await page.unroute('**/api/operator/ai/models');
  const woo=page.locator('.provider-card').filter({has:page.getByRole('heading',{name:'WooCommerce',exact:true})});
  await woo.getByRole('button',{name:'Configure',exact:true}).click();
  await page.getByLabel('WooCommerce URL',{exact:true}).fill('https://staging.example.test');
  await page.getByRole('button',{name:'Save configuration',exact:true}).click();
  await page.locator('#modal').waitFor({state:'hidden'});
  assert((await c.settings.envDocument()).values.WOO_URL==='https://staging.example.test');
  await visit('team','Team & access');
  await page.getByRole('button',{name:'Add team member',exact:true}).click();
  await page.getByLabel('Email address',{exact:true}).fill('support@example.test');
  await page.getByLabel('Temporary password',{exact:true}).fill('support-browser-password-123');
  await page.getByRole('button',{name:'Create member',exact:true}).click();
  await page.locator('#modal').waitFor({state:'hidden'});
  await page.locator('table').getByText('support@example.test',{exact:true}).waitFor();
  await visit('overview','Overview');
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Mobile page must not overflow horizontally');
  await page.screenshot({path:'artifacts/panel-mobile.png',fullPage:true});
  assert.deepEqual(errors,[],'No browser JavaScript errors');
  console.log('Browser checks passed: navigation, checkout, payment, settings, credentials, team, and mobile layout. Screenshots saved to artifacts/.');
} finally {
  clearInterval(timer);
  if(browser)await browser.close();
  if(server.listening)await new Promise(resolve=>server.close(resolve));
  await c.store.close();
  await rm(directory,{recursive:true,force:true});
}
